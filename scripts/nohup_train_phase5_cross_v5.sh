#!/bin/bash
set -euo pipefail

# One-command background launcher for Phase 5.5 Cross V5-min training.
# Usage:
#   bash scripts/nohup_train_phase5_cross_v5.sh
#
# Optional env overrides are forwarded to train_phase5_cross_v5.sh, for example:
#   GPU_IDS=1,2,4 MAX_TRAIN_STEPS=500 bash scripts/nohup_train_phase5_cross_v5.sh

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
