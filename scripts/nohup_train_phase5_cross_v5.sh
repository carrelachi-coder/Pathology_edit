  "cross_v5_geometry_predictor_mask2former_queries": "${CROSS_V5_GEOMETRY_PREDICTOR_MASK2FORMER_QUERIES}",
  "cross_v5_geometry_predictor_ignore_index": "${CROSS_V5_GEOMETRY_PREDICTOR_IGNORE_INDEX}",
  "cross_v5_pairing_sampler": "${CROSS_V5_PAIRING_SAMPLER}",
  "cross_v5_pairs_per_epoch": "${CROSS_V5_PAIRS_PER_EPOCH}",
  "cross_v5_same_wsi_fraction": "${CROSS_V5_SAME_WSI_FRACTION}",
  "cross_v5_cross_wsi_fraction": "${CROSS_V5_CROSS_WSI_FRACTION}",
  "cross_v5_high_appearance_gap_fraction": "${CROSS_V5_HIGH_APPEARANCE_GAP_FRACTION}",
  "cross_v5_full_coverage_fraction": "${CROSS_V5_FULL_COVERAGE_FRACTION}",
  "cross_v5_partial_coverage_fraction": "${CROSS_V5_PARTIAL_COVERAGE_FRACTION}",
  "cross_v5_low_coverage_fraction": "${CROSS_V5_LOW_COVERAGE_FRACTION}",
  "cross_v5_class_bank_dropout_prob": "${CROSS_V5_CLASS_BANK_DROPOUT_PROB}",
  "cross_v5_high_gap_quantile": "${CROSS_V5_HIGH_GAP_QUANTILE}",
  "cross_v5_min_ref_presence_tokens": "${CROSS_V5_MIN_REF_PRESENCE_TOKENS}",
  "cross_v5_min_bank_token_confidence": "${CROSS_V5_MIN_BANK_TOKEN_CONFIDENCE}",
  "cross_v5_local_tokens_per_class": "${CROSS_V5_LOCAL_TOKENS_PER_CLASS}",
