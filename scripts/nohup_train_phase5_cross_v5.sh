CROSS_V5_VGG_ALLOW_DOWNLOAD="${CROSS_V5_VGG_ALLOW_DOWNLOAD:-1}"
CROSS_V5_APPEARANCE_INTERVAL="${CROSS_V5_APPEARANCE_INTERVAL:-1}"
CROSS_V5_GEOMETRY_INTERVAL="${CROSS_V5_GEOMETRY_INTERVAL:-4}"
