export PROJECT_ROOT
export CROSS_V5_OUTPUT_DIR
export GPU_IDS
export MAX_CUDA_MEMORY_GB
export MAX_TRAIN_STEPS
export LR_WARMUP_STEPS
export CHECKPOINTING_STEPS
export GRADIENT_CHECKPOINTING
export CROSS_V5_DENOISE_WEIGHT
export CROSS_V5_APPEARANCE_WEIGHT
export CROSS_V5_GEOMETRY_WEIGHT
export CROSS_V5_TEXTURE_WEIGHT
export CROSS_V5_COLOR_WEIGHT
export CROSS_V5_COLOR_SPACE
export CROSS_V5_VGG_WEIGHTS_PATH
