TRAIN_SCRIPT="${TRAIN_SCRIPT:-${SCRIPT_DIR}/train_phase5_cross_v5.sh}"

PROJECT_ROOT="${PROJECT_ROOT:-/home/lyw/wqx-DL/flow-edit/FlowEdit-main}"
CROSS_V5_OUTPUT_DIR="${CROSS_V5_OUTPUT_DIR:-/data/wqx/flowedit/controlnet_cross_v5_min}"
LOG_ROOT="${LOG_ROOT:-${CROSS_V5_OUTPUT_DIR}/nohup_logs}"
RUN_NAME="${RUN_NAME:-cross_v5_$(date +%Y%m%d_%H%M%S)}"
LOG_FILE="${LOG_FILE:-${LOG_ROOT}/${RUN_NAME}.log}"
